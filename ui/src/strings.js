function interpolate(template, params = {}) {
  return String(template).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

/**
 * Returns a reactive translation function backed by `kt.t()`,
 * falling back cleanly to English defaults if a bundle is not loaded.
 */
export function useRoleplayText() {
  const locale = useLocale();
  let kt = null;
  try {
    kt = useExtension();
  } catch {
    kt = null;
  }
  return (key, params = {}) => {
    void locale.value;
    if (kt && typeof kt.t === "function") {
      const resolved = kt.t(key, params);
      if (resolved && resolved !== key) return resolved;
    }
    const fallback = EN_FALLBACK[key];
    return fallback ? interpolate(fallback, params) : key;
  };
}
